  const listeners = new Set();
  let lang = 'en';

  function format(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
  }

  function t(key, vars) {
    const table = DICT[lang] || DICT.en;
    const raw = table[key] != null ? table[key] : (DICT.en[key] != null ? DICT.en[key] : key);
    return format(raw, vars);
  }

  function setLang(next, opts) {
    const value = next === 'ar' ? 'ar' : 'en';
    const changed = value !== lang;
    lang = value;
    const root = document.documentElement;
    root.lang = lang;
    root.dir = lang === 'ar' ? 'rtl' : 'ltr';
    root.classList.toggle('rtl', lang === 'ar');
    if (!opts || opts.silent !== true) {
      for (const fn of listeners) { try { fn(lang, changed); } catch {} }
    }
    return lang;
  }

  function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

  /** Fills every data-i18n / data-i18n-title / data-i18n-ph node. */
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
      if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', el.title);
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
  }

  function getLang() { return lang; }

  window.i18n = { t, setLang, getLang, apply, onChange, DICT };
  // Short global helper for templates.
  window.t = t;
